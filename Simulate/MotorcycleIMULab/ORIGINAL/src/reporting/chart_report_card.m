function html = chart_report_card(titleText, imagePath, pngPath, readableWidth)
    % CHART_REPORT_CARD Display a sharp chart with readable-size and fit-width modes.
    % Paths are relative to the HTML page; vector SVG is preferred when available.

    html = sprintf(['<section class="chart-card"><h2>%s</h2>' ...
                    '<div class="toolbar"><button onclick="setChartMode(this,false)">Readable size</button>' ...
                    '<button class="secondary" onclick="setChartMode(this,true)">Fit width</button>' ...
                    '<a class="button secondary" href="%s" target="_blank">Open full-size chart</a>' ...
                    '<a href="%s" download>Download high-resolution PNG</a></div>' ...
                    '<p class="help">Default: large labels and horizontal scrolling. SVG stays sharp when zoomed. Use Fit width only when you want a smaller overview.</p>' ...
                    '<div class="chart-shell"><img style="--chart-width:%dpx" src="%s" alt="%s"></div></section>'], ...
                   titleText, imagePath, pngPath, readableWidth, imagePath, titleText);
end
