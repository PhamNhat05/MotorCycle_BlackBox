function write_augmented_report(runDirectory, plan, manifest, config)
    % WRITE_AUGMENTED_REPORT Build high-contrast indexes with one page per variant.
    % Outputs: global INDEX.html, parent INDEX.html files and parameter summaries.

    writetable(struct2table(plan), fullfile(runDirectory, 'VARIANT_MANIFEST.csv'));
    groups = {'bias_only', 'position_only', 'bias_and_position'};
    counts = zeros(numel(manifest), 4);
    for parentIndex = 1:numel(manifest)
        key = manifest(parentIndex).key;
        indices = find(strcmp({plan.ParentKey}, key));
        rows = {};
        directory = fullfile(runDirectory, 'records', key);
        if ~isfolder(directory)
            mkdir(directory);
        end
        for recipeIndex = indices
            recipe = plan(recipeIndex);
            state = 'PENDING';
            links = 'Waiting for export';
            if recipe.Materialized
                state = 'COMPLETE';
                stem = sprintf('variant_%03d', recipe.VariantIndex);
                links = sprintf(['<a class="button" href="%s/%s.html">Open detailed report</a>' ...
                                 ' <a href="%s/%s.png">PNG</a> | <a href="%s/%s.csv">CSV</a> | ' ...
                                 '<a href="%s/%s_STATS.csv">Metrics</a>'], ...
                                recipe.Group, stem, recipe.Group, stem, recipe.Group, stem, recipe.Group, stem);
            end
            rows{end + 1} = sprintf(['<tr><td><strong>%03d</strong></td><td>%s</td>' ...
                                     '<td>[%+.4f, %+.4f, %+.4f]</td><td>[%+.4f, %+.4f, %+.4f]</td>' ...
                                     '<td>[%+.4f, %+.4f, %+.4f]</td><td>%s</td><td>%s</td></tr>'], ...
                                    recipe.VariantIndex, strrep(recipe.Group, '_', ' '), ...
                                    recipe.DeltaX_m, recipe.DeltaY_m, recipe.DeltaZ_m, ...
                                    recipe.DeltaAx, recipe.DeltaAy, recipe.DeltaAz, ...
                                    recipe.DeltaGx, recipe.DeltaGy, recipe.DeltaGz, state, links);
        end
        for groupIndex = 1:3
            counts(parentIndex, groupIndex) = sum( ...
                                                  strcmp({plan(indices).Group}, groups{groupIndex}) & [plan(indices).Materialized]);
        end
        counts(parentIndex, 4) = sum([plan(indices).Materialized]);
        page = [report_header([key ': augmented variants']) ...
                '<h1>' key ': 100 separate variants</h1><section class="card">' ...
                '<p>Each detailed report compares one augmented recording with its original measured parent. Charts show the position, bias and baseline-error components separately.</p>' ...
                '<p><a href="../../INDEX.html">Back to all source recordings</a></p>' ...
                '<label><strong>Find a variant:</strong> <input placeholder="ID, group or parameter" oninput="filterRows(this)"></label></section>' ...
                '<div class="table-scroll"><table><thead><tr><th>ID</th><th>Group</th>' ...
                '<th>Position shift XYZ (m)</th><th>Acceleration bias (m/s^2)</th>' ...
                '<th>Gyroscope bias (deg/s)</th><th>Status</th><th>Report and data</th>' ...
                '</tr></thead><tbody data-filter>' strjoin(rows, newline) ...
                '</tbody></table></div></main></body></html>'];
        write_html_file(fullfile(directory, 'INDEX.html'), page);
    end

    summary = table(string({manifest.key})', string({manifest.split})', ...
                    [manifest.record_contains_fall]', counts(:, 1), counts(:, 2), counts(:, 3), counts(:, 4), ...
                    'VariableNames', {'Parent', 'OriginalSplit', 'RecordContainsFall', ...
                          'BiasComplete', 'PositionComplete', 'CombinedComplete', 'TotalComplete'});
    writetable(summary, fullfile(runDirectory, 'PARENT_SUMMARY.csv'));
    complete = sum([plan.Materialized]);
    page = [report_header('Augmented dataset report') ...
            '<h1>Augmented dataset report</h1>' sprintf( ...
                                                    '<div class="kpis"><div class="kpi"><strong>%d / 1000</strong>Completed variants</div><div class="kpi"><strong>100 per source</strong>34 bias + 33 position + 33 combined</div></div>', complete) ...
            sprintf(['<section class="card"><p><strong>Position:</strong> shift length up to %.3g m. ' ...
                 '<strong>Acceleration bias:</strong> up to %.3g m/s^2 per axis. ' ...
                 '<strong>Gyroscope bias:</strong> up to %.3g deg/s per axis.</p>'], ...
                config.position_delta_max_norm_m, max(config.acc_bias_delta_bound_m_s2), ...
                max(config.gyro_bias_delta_bound_deg_s)) ...
            '<p><a href="VARIANT_MANIFEST.csv">All variant parameters</a> | <a href="ALL_AXIS_METRICS.csv">All axis metrics</a> | <a href="PARENT_SUMMARY.csv">Parent summary</a></p>' ...
            '<p>Open a source recording, then select one detailed variant report. Each report includes a vector chart and a high-resolution PNG.</p></section>' ...
            '<div class="table-scroll"><table><thead><tr><th>Original source</th><th>Split</th>' ...
            '<th>Bias</th><th>Position</th><th>Combined</th><th>Completed</th></tr></thead><tbody>'];
    for parentIndex = 1:numel(manifest)
        page = [page sprintf(['<tr><td><a href="records/%s/INDEX.html">%s</a></td><td>%s</td>' ...
                              '<td>%d / 34</td><td>%d / 33</td><td>%d / 33</td><td><strong>%d / 100</strong></td></tr>'], ...
                             manifest(parentIndex).key, manifest(parentIndex).key, ...
                             upper(manifest(parentIndex).split), counts(parentIndex, :))];
    end
    page = [page '</tbody></table></div><footer>The original 7 BUILD / 3 TEST grouping is retained. Keep every original parent and all its variants in the same ML split. TEST descendants are stress tests.</footer></main></body></html>'];
    write_html_file(fullfile(runDirectory, 'INDEX.html'), page);
end
