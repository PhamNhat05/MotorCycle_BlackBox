function write_variant_report(files, record, recipe, definition, metrics, config)
    % WRITE_VARIANT_REPORT Create a readable, self-contained page for one variant.
    % The page embeds SVG when enabled and links full CSV, PNG, JSON and metrics.

    [~, stem] = fileparts(files.csv);
    imageName = [stem '.png'];
    if config.export_svg
        imageName = [stem '.svg'];
    end
    titleText = sprintf('%s | variant %03d', record.key, recipe.VariantIndex);
    shift = definition.position_delta_body_m;
    bias = definition.bias_delta;
    page = [report_header(titleText) '<h1>' titleText '</h1>' ...
            '<p><a href="../INDEX.html">Back to this source</a> | <a href="../../../INDEX.html">All sources</a></p>' ...
            '<section class="card"><h2>Exact changes applied</h2>' ...
            sprintf(['<p><strong>Group:</strong> %s</p><p><strong>Position shift XYZ:</strong> ' ...
                 '[%+.5f, %+.5f, %+.5f] m; <strong>shift length:</strong> %.5f m.</p>' ...
                 '<p><strong>Acceleration bias XYZ:</strong> [%+.5f, %+.5f, %+.5f] m/s^2.</p>' ...
                 '<p><strong>Gyroscope bias XYZ:</strong> [%+.5f, %+.5f, %+.5f] deg/s.</p>' ...
                 '<p><strong>Samples:</strong> %d; <strong>source interval:</strong> %.3f to %.3f s.</p>'], ...
                strrep(recipe.Group, '_', ' '), shift, norm(shift), bias(1:3), bias(4:6), ...
                definition.samples, definition.source_first_s, definition.source_last_s) ...
            sprintf(['<div class="toolbar"><a href="%s.csv">Full signal CSV</a> | ' ...
                 '<a href="%s_STATS.csv">Six-axis metrics</a> | <a href="%s.json">Parameters and provenance</a></div></section>'], stem, stem, stem)];
    page = [page chart_report_card('Original signal and exactly one augmented variant', ...
                                   imageName, [stem '.png'], 2250) ...
            '<section class="card"><h2>Full-record changes by axis</h2>' ...
            '<p>Total difference = position component + bias component + baseline reconstruction error.</p>' ...
            '<div class="table-scroll"><table><thead><tr><th>Axis</th><th>Unit</th>' ...
            '<th>RMSE vs original</th><th>Maximum absolute difference</th><th>Peak time (s)</th>' ...
            '<th>Position RMS</th><th>Bias offset</th><th>Baseline RMS</th></tr></thead><tbody>'];
    for axisIndex = 1:6
        page = [page sprintf(['<tr><td><strong>%s</strong></td><td>%s</td>' ...
                              '<td class="num">%.6g</td><td class="num">%.6g</td><td class="num">%.3f</td>' ...
                              '<td class="num">%.6g</td><td class="num">%+.6g</td><td class="num">%.6g</td></tr>'], ...
                             char(string(metrics.Axis(axisIndex))), char(string(metrics.Unit(axisIndex))), ...
                             metrics.RMSE_vs_original(axisIndex), metrics.MaxAbs_vs_original(axisIndex), ...
                             metrics.TimeMaxAbs_s(axisIndex), metrics.RMSE_position_component(axisIndex), ...
                             metrics.BiasDelta(axisIndex), metrics.RMSE_baseline_vs_original(axisIndex))];
    end
    page = [page '</tbody></table></div></section>' ...
            '<footer>Only the sensor position and constant electronic bias are changed. The underlying motion, source timestamps and mounting orientation are preserved. Metrics use every sample.</footer></main></body></html>'];
    write_html_file(files.report, page);
end
