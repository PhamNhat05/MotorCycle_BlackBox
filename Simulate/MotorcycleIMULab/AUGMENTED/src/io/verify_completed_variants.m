function plan = verify_completed_variants(runDirectory, plan, config)
    % VERIFY_COMPLETED_VARIANTS Reconcile verified completion markers with recipes.
    % A CSV alone is not complete: plot, metrics and parameter files must also exist.

    for index = 1:numel(plan)
        files = get_variant_paths(runDirectory, plan(index));
        if ~isfile(files.completion)
            continue
        end
        completed = jsondecode(fileread(files.completion));
        assert(isfile(files.csv) && isfile(files.plot) && isfile(files.metrics) ...
               && isfile(files.definition) && isfile(files.report), ...
               'A committed variant is missing a data, chart or report output.');
        if config.export_svg
            assert(isfile(files.vector) && completed.vector_exported, ...
                   'A committed vector chart is missing.');
        end
        assert(completed.samples == plan(index).Samples ...
               && completed.variant_index == plan(index).VariantIndex ...
               && strcmp(completed.parent_key, plan(index).ParentKey), ...
               'A completion marker belongs to another recipe.');
        if config.resume_verify_hashes
            assert(strcmp(hash_file(files.csv), completed.csv_sha256) ...
                   && strcmp(hash_file(files.plot), completed.png_sha256) ...
                   && strcmp(hash_file(files.metrics), completed.stats_sha256) ...
                   && strcmp(hash_file(files.definition), completed.definition_sha256), ...
                   'A committed augmentation output changed: %s', files.csv);
            assert(strcmp(hash_file(files.report), completed.report_sha256), ...
                   'A committed variant report changed: %s', files.report);
            if config.export_svg
                assert(strcmp(hash_file(files.vector), completed.svg_sha256), ...
                       'A committed vector chart changed: %s', files.vector);
            end
        end
        plan(index).Materialized = true;
    end
end
