function export_augmented_variant(runDirectory, model, sampled, record, recipe, config, context, parentIndex)
    % EXPORT_AUGMENTED_VARIANT Write full CSV, sharp charts and one detailed HTML page.
    % Completion is committed last, after every data/chart/report file succeeds.

    variant = compute_sensor_variant(model, sampled, recipe, config);
    time = model.time_source_s;
    count = numel(time);
    files = get_variant_paths(runDirectory, recipe);
    directory = fileparts(files.csv);
    if ~isfolder(directory)
        mkdir(directory);
    end

    % Store the exact recipe and its original-parent provenance.
    shift = variant.position_delta_body_m;
    bias = variant.bias_delta;
    definition = struct('parent_key', record.key, 'parent_split', record.split, ...
                        'record_contains_fall', record.record_contains_fall, ...
                        'holdout_stress_only', strcmp(record.split, 'test'), ...
                        'variant_index', recipe.VariantIndex, 'group', recipe.Group, 'samples', count, ...
                        'source_first_s', time(1), 'source_last_s', time(end), ...
                        'position_delta_body_m', shift, 'position_delta_norm_m', norm(shift), ...
                        'position_body_m', model.K.nominal_position_body_m + shift, ...
                        'bias_delta', bias, 'bias_total', model.K.bias + bias, ...
                        'position_units', 'm', 'acc_bias_units', 'm/s^2', 'gyro_bias_units', 'deg/s', ...
                        'parent_model_sha256', context.modelHashes{parentIndex}, ...
                        'frozen_configuration_sha256', context.frozenHash, 'scope', config.scope, ...
                        'timing_preserved', true, 'mounting_rotation_preserved', true, ...
                        'hardware_bounds_validated', false, ...
                        'forward_consistency_max_abs', variant.forward_consistency_max_abs);

    % All samples are exported and scored; display reduction affects only plots.
    headers = {'Time_s', 'Ax_m_s2', 'Ay_m_s2', 'Az_m_s2', ...
               'Gx_deg_s', 'Gy_deg_s', 'Gz_deg_s'};
    write_numeric_csv(files.csv, headers, [time variant.signals]);
    metrics = compute_variant_metrics(time, model.measured_imu, sampled.imu, ...
                                      variant.signals, variant.position_component, bias);
    writetable(metrics, files.metrics);
    temporaryPlot = [files.plot '.partial.png'];
    temporaryVector = [files.vector '.partial.svg'];
    definition.zoom = plot_augmented_comparison(temporaryPlot, temporaryVector, ...
                                                model, sampled, variant, record, recipe, metrics, config);
    movefile(temporaryPlot, files.plot, 'f');
    if config.export_svg
        movefile(temporaryVector, files.vector, 'f');
    end
    write_json(files.definition, definition);
    write_variant_report(files, record, recipe, definition, metrics, config);

    % A resume operation trusts only this final marker and matching hashes.
    completed = struct('parent_key', record.key, 'variant_index', recipe.VariantIndex, ...
                       'samples', count, 'csv_sha256', hash_file(files.csv), ...
                       'png_sha256', hash_file(files.plot), 'stats_sha256', hash_file(files.metrics), ...
                       'definition_sha256', hash_file(files.definition), ...
                       'report_sha256', hash_file(files.report), 'vector_exported', config.export_svg, ...
                       'forward_consistency_max_abs', variant.forward_consistency_max_abs, ...
                       'all_outputs_complete', true);
    if config.export_svg
        completed.svg_sha256 = hash_file(files.vector);
    end
    write_json(files.completion, completed);
end
